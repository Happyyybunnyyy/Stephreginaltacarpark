export function getAvailabilityStatus(availableLots: number): {
  label: string;
  color: string;
  bg: string;
  border: string;
  dotColor: string;
  status: 'abundant' | 'moderate' | 'limited' | 'full';
} {
  if (availableLots === 0) {
    return {
      label: 'Full (0 lots)',
      color: 'text-rose-700',
      bg: 'bg-rose-50',
      border: 'border-rose-200',
      dotColor: 'bg-rose-600',
      status: 'full',
    };
  }
  if (availableLots < 15) {
    return {
      label: 'Filling Fast',
      color: 'text-rose-600',
      bg: 'bg-rose-50',
      border: 'border-rose-200',
      dotColor: 'bg-rose-500',
      status: 'limited',
    };
  }
  if (availableLots < 50) {
    return {
      label: 'Moderate',
      color: 'text-amber-700',
      bg: 'bg-amber-50',
      border: 'border-amber-200',
      dotColor: 'bg-amber-500',
      status: 'moderate',
    };
  }
  return {
    label: 'Lots Available',
    color: 'text-emerald-700',
    bg: 'bg-emerald-50',
    border: 'border-emerald-200',
    dotColor: 'bg-emerald-500',
    status: 'abundant',
  };
}
